"""Generate a typed declaration for each complete design-sheet row."""

import argparse
import hashlib
import json
from pathlib import Path
from preflight import ROOT, inspect


def render(directory):
    sheets, issues, _ = inspect(directory)
    if issues:
        raise ValueError('\n'.join(issues))
    canonical = json.dumps(sheets, sort_keys=True, separators=(',', ':')).encode()
    lines = ['# Generated by tools/generate_design.py. Edit sheets, never this file.',
             'from dataclasses import dataclass', '',
             f'SHEET_SHA256 = {hashlib.sha256(canonical).hexdigest()!r}', '']
    for name, sheet in sheets.items():
        class_name = sheet['class']
        lines += ['@dataclass(frozen=True)', f'class {class_name}:']
        for column, spec in sheet['columns'].items():
            annotation = {'str': 'str', 'int': 'int', 'float': 'float', 'bool': 'bool', 'color': 'tuple[int, int, int]'}[spec['type']]
            lines.append(f'    {column}: {annotation}')
        lines.append('')
        members = []
        for row in sheet['rows']:
            symbol = (name + '_' + row['id']).upper().replace('-', '_')
            values = []
            for column, spec in sheet['columns'].items():
                value = tuple(row[column]) if spec['type'] == 'color' else row[column]
                values.append(f'{column}={value!r}')
            lines.append(f'{symbol} = {class_name}({", ".join(values)})')
            members.append((row['id'], symbol))
        lines.append(f'{name.upper()} = {{{", ".join(repr(k) + ": " + v for k, v in members)}}}')
        lines.append('')
    return '\n'.join(lines).rstrip() + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'src/deltadash/generated_design.py'
    expected = render(ROOT / 'sheets')
    if args.check:
        if not path.exists() or path.read_text() != expected:
            print('Generated design is stale. Run python tools/generate_design.py.')
            return 1
    else:
        path.write_text(expected)
        print(f'Generated {path.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
