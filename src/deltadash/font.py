def measure(text: str, scale=1):
    return max(0, len(text) * 6 - 1) * scale


def draw(surface, text, position, color=(245, 244, 252), scale=1, center=False):
    import pygame
    x, y = position
    if center:
        x -= measure(text, scale) // 2
    for char in text.upper():
        for row, bits in enumerate(GLYPHS.get(char, GLYPHS['?'])):
            for col, bit in enumerate(bits):
                if bit == '1':
                    pygame.draw.rect(surface, color, (int(x + col*scale), int(y + row*scale), scale, scale))
        x += 6 * scale


def wrap(text: str, width: int):
    lines, line = [], ''
    for word in text.upper().split():
        if len(line) + len(word) + bool(line) > width:
            if line:
                lines.append(line)
            line = ''
        while len(word) > width:
            lines.append(word[:width])
            word = word[width:]
        line += (' ' if line else '') + word
    if line:
        lines.append(line)
    return lines
